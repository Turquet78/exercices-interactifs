-- ---------------------------------------------------------------- TERMINALE
create table if not exists public.eleves (
  id uuid primary key default gen_random_uuid(),
  prenom text not null,
  pin text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.resultats (
  id uuid primary key default gen_random_uuid(),
  eleve_id uuid not null references public.eleves(id) on delete cascade,
  score integer, total integer, percent integer,
  duration_sec numeric,                       -- numeric ici, integer ailleurs
  details jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.parametres (
  id integer primary key,
  valeurs jsonb
);

-- ----------------------------------------------------------------- PREMIÈRE
-- Le seul niveau en bigint. C'est lui que la supposition « tout est uuid »
-- aurait cassé, et lui seul.
create table if not exists public.eleves_1ere (
  id bigint generated by default as identity primary key,
  prenom text not null,
  pin text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.resultats_1ere (
  id bigint generated by default as identity primary key,
  eleve_id bigint not null references public.eleves_1ere(id) on delete cascade,
  score numeric, total integer, percent integer, duration_sec integer,
  details jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.parametres_1ere (
  id integer primary key,
  valeurs jsonb
);

-- ------------------------------------------------------------------ SECONDE
create table if not exists public.eleves_2nde (
  id uuid primary key default gen_random_uuid(),
  prenom text not null,
  pin text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.resultats_2nde (
  id uuid primary key default gen_random_uuid(),
  eleve_id uuid not null references public.eleves_2nde(id) on delete cascade,
  score numeric, total integer, percent numeric, duration_sec integer,
  details jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.parametres_2nde (
  id integer primary key,
  valeurs jsonb
);

