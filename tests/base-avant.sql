--  RELEVÉ SUR LE PROJET le 10 août 2026 (information_schema.columns), pas
--  supposé. La première version de ce fichier était une reconstitution de
--  mémoire : elle déclarait « id uuid » partout. C'était faux, et le banc a
--  donc validé du code qui aurait cassé la création de compte en Première —
--  où les identifiants sont des bigint.
--
--  LES TROIS NIVEAUX N'ONT PAS LA MÊME STRUCTURE. C'est le fait central que
--  ce fichier doit préserver :
--
--      Terminale  eleves.id        uuid      resultats.eleve_id      uuid
--      Première   eleves_1ere.id   BIGINT    resultats_1ere.eleve_id BIGINT
--      Seconde    eleves_2nde.id   uuid      resultats_2nde.eleve_id uuid
--
--  Les types des colonnes de notes diffèrent aussi d'un niveau à l'autre
--  (score numeric ici, integer là ; duration_sec numeric en Terminale). Ils
--  sont reproduits à l'identique : c'est ce genre d'écart qui fait qu'un
--  contrôle passe sur un niveau et casse sur un autre.
--
--  Si la structure du projet change, RELEVEZ-LA À NOUVEAU plutôt que de
--  corriger ce fichier de tête. La requête est dans supabase/LISEZMOI.md.
